//! Specifier classification and resolution.
//!
//! | Specifier | Resolution |
//! |---|---|
//! | `./x.ts`, `../y.js` | Bundle files |
//! | `std:kv|sql|sqlite|blob|queue|services|platform|sdk|…`, `bun:sqlite` (= `std:sqlite`) | Built-in (from the base snapshot, not bundled) |
//! | `sdk:<name>`, and `std:sdk` in a tenant module | A shim generated from the published SDK contract (`crate::sdk_shim`), never SDK code |
//! | `npm:pkg@range[/sub]` | `{build.npm_cdn}/pkg@range[/sub]?target=es2022` |
//! | `jsr:@scope/pkg@range` | `{build.npm_cdn}/jsr/@scope/pkg@range?target=es2022` |
//! | `https://host/...` | Only if `host ∈ build.allowed_hosts` |
//! | import map (`rt.json.imports`) | Applied before the rules above |
//! | anything else (`file:`, `node:` not allowlisted, bare, unknown `sdk:`) | `422` at deploy |

use std::collections::BTreeMap;

use thiserror::Error;
use url::Url;

/// Syntactic class of an import specifier (no configuration needed).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum SpecifierKind {
    Relative,
    /// `rt:…`
    Builtin,
    /// `sdk:…`
    Sdk,
    Npm,
    Jsr,
    /// `http://` or `https://`
    Remote,
    /// `file:` — always rejected.
    File,
    /// `node:` — rejected unless allowlisted.
    Node,
    /// Bare (`lodash`) — only valid through an import map.
    Bare,
}

/// Classify by prefix.
pub fn classify_specifier(s: &str) -> SpecifierKind {
    if s.starts_with("./") || s.starts_with("../") || s.starts_with('/') {
        SpecifierKind::Relative
    } else if s.starts_with("std:") || s.starts_with("rt:") || builtin_alias(s).is_some() {
        // `rt:*` is classified as built-in too, so that a guest still importing a renamed module
        // gets the rename error rather than "unsupported specifier".
        SpecifierKind::Builtin
    } else if s.starts_with("sdk:") {
        SpecifierKind::Sdk
    } else if s.starts_with("npm:") {
        SpecifierKind::Npm
    } else if s.starts_with("jsr:") {
        SpecifierKind::Jsr
    } else if s.starts_with("https://") || s.starts_with("http://") {
        SpecifierKind::Remote
    } else if s.starts_with("file:") {
        SpecifierKind::File
    } else if s.starts_with("node:") {
        SpecifierKind::Node
    } else {
        SpecifierKind::Bare
    }
}

/// The built-in `std:*` modules guests may import.
pub const BUILTIN_MODULES: &[&str] = &[
    "std:kv",
    "std:sql",
    "std:sqlite",
    "std:blob",
    "std:queue",
    "std:services",
    "std:platform",
    "std:log",
    "std:secrets",
    "std:lock",
    "std:schedule",
    "std:sockets",
    "std:durable",
    "std:sdk",
    "std:sdk/server",
];

/// Other names of built-in modules, rewritten to the `std:*` name in the bundle: bun code that
/// imports `bun:sqlite` runs unchanged on `std:sqlite`.
pub const BUILTIN_ALIASES: &[(&str, &str)] = &[("bun:sqlite", "std:sqlite")];

/// The `std:*` module `specifier` is another name of.
pub fn builtin_alias(specifier: &str) -> Option<&'static str> {
    BUILTIN_ALIASES
        .iter()
        .find(|(alias, _)| *alias == specifier)
        .map(|(_, target)| *target)
}

/// Built-in modules that were renamed before release: `(old, new)`. Importing an old name is a
/// build error that names the new one.
pub const RENAMED_MODULES: &[(&str, &str)] = &[
    ("rt:kv", "std:kv"),
    ("rt:sql", "std:sql"),
    ("rt:sqlite", "std:sqlite"),
    ("rt:blob", "std:blob"),
    ("rt:queue", "std:queue"),
    ("rt:services", "std:services"),
    ("rt:platform", "std:platform"),
];

/// The new name of a renamed built-in module (`rt:kv` -> `std:kv`), if `specifier` is an old name.
pub fn renamed_to(specifier: &str) -> Option<&'static str> {
    RENAMED_MODULES
        .iter()
        .find(|(old, _)| *old == specifier)
        .map(|(_, new)| *new)
}

/// Result of resolving one specifier.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum Resolved {
    /// A file inside the uploaded archive (normalized `file:///path`).
    Local(Url),
    /// Provided by the runtime (not bundled).
    Builtin(String),
    /// Generated by the build (an operator SDK shim, `crate::sdk_shim`): bundled from `source`.
    Generated { url: Url, source: String },
    /// Must be fetched (through the egress guard) and bundled.
    Remote(Url),
}

#[derive(Debug, Clone, PartialEq, Eq, Error)]
pub enum ResolveError {
    #[error("unsupported specifier `{0}`")]
    Unsupported(String),
    #[error("host `{0}` is not in build.allowed_hosts")]
    HostNotAllowed(String),
    #[error("unknown sdk `{0}`")]
    UnknownSdk(String),
    #[error("unknown runtime module `{0}`")]
    UnknownBuiltin(String),
    #[error("`{from}` was renamed to `{to}`")]
    Renamed { from: String, to: String },
    #[error("invalid specifier `{0}`")]
    Invalid(String),
}

pub trait SpecifierResolver: Send + Sync {
    /// Resolve `specifier` as imported from `referrer` (a `file:///…` or remote URL).
    fn resolve(&self, specifier: &str, referrer: &Url) -> Result<Resolved, ResolveError>;
}

#[derive(Clone, Debug)]
pub struct ResolverConfig {
    /// `build.npm_cdn`.
    pub npm_cdn: Url,
    /// `build.allowed_hosts`.
    pub allowed_hosts: Vec<String>,
    /// `rt.json` `imports`, applied first.
    pub import_map: BTreeMap<String, String>,
}

/// Default implementation of the table above.
pub struct DefaultResolver {
    cfg: ResolverConfig,
}

impl DefaultResolver {
    pub fn new(cfg: ResolverConfig) -> Self {
        Self { cfg }
    }

    fn host_allowed(&self, host: &str) -> bool {
        let host = host.trim_end_matches('.');
        self.cfg
            .allowed_hosts
            .iter()
            .any(|h| h.trim_end_matches('.').eq_ignore_ascii_case(host))
    }

    /// Accept a remote URL only for `https` (or `http` to a loopback mirror) and an allow-listed
    /// host. Plain `http` over the network is refused: its bytes are not verified, and the deps
    /// cache would share them with every tenant's builds.
    fn remote(&self, url: Url) -> Result<Resolved, ResolveError> {
        let loopback = match url.host() {
            Some(url::Host::Ipv4(a)) => a.is_loopback(),
            Some(url::Host::Ipv6(a)) => a.is_loopback(),
            Some(url::Host::Domain(d)) => d.eq_ignore_ascii_case("localhost"),
            None => false, // LCOV_EXCL_LINE: an http(s) URL always has a host
        };
        if url.scheme() != "https" && !(url.scheme() == "http" && loopback) {
            return Err(ResolveError::Unsupported(url.to_string()));
        }
        // Credentials in an import URL would reach build logs and error messages.
        if !url.username().is_empty() || url.password().is_some() {
            let mut shown = url.clone();
            let _ = shown.set_username("");
            let _ = shown.set_password(None);
            return Err(ResolveError::Invalid(format!("{shown} (credentials in an import URL)")));
        }
        // LCOV_EXCL_START: an http(s) URL always has a host
        let Some(host) = url.host_str() else {
            return Err(ResolveError::Invalid(url.to_string()));
        };
        // LCOV_EXCL_STOP
        if !self.host_allowed(host) {
            return Err(ResolveError::HostNotAllowed(host.to_string()));
        }
        Ok(Resolved::Remote(url))
    }

    /// `import map` lookup: exact key first, then the longest `prefix/` key.
    fn map_specifier(&self, specifier: &str) -> Option<String> {
        if let Some(t) = self.cfg.import_map.get(specifier) {
            return Some(t.clone());
        }
        self.cfg
            .import_map
            .iter()
            .filter(|(k, _)| k.ends_with('/') && specifier.starts_with(k.as_str()))
            .max_by_key(|(k, _)| k.len())
            .map(|(k, t)| format!("{t}{}", &specifier[k.len()..]))
    }

    fn cdn_url(&self, tail: &str) -> Result<Url, ResolveError> {
        let base = self.cfg.npm_cdn.as_str().trim_end_matches('/');
        let tail = tail.trim_start_matches('/');
        let url =
            Url::parse(&format!("{base}/{tail}?target=es2022")).map_err(|_| ResolveError::Invalid(tail.to_string()))?;
        // LCOV_EXCL_START: a path appended to `npm_cdn` cannot change its host or port
        if url.host_str() != self.cfg.npm_cdn.host_str() || url.port() != self.cfg.npm_cdn.port() {
            return Err(ResolveError::Invalid(tail.to_string()));
        }
        // LCOV_EXCL_STOP
        Ok(url)
    }

    fn relative(&self, specifier: &str, referrer: &Url) -> Result<Resolved, ResolveError> {
        let joined = referrer
            .join(specifier)
            .map_err(|_| ResolveError::Invalid(specifier.to_string()))?;
        match joined.scheme() {
            "file" => {
                // A `file:` module can only reach other bundle files: no host, no query.
                if joined.host_str().is_some_and(|h| !h.is_empty())
                    || joined.query().is_some()
                    || joined.fragment().is_some()
                {
                    return Err(ResolveError::Invalid(specifier.to_string()));
                }
                Ok(Resolved::Local(joined))
            }
            "http" | "https" => self.remote(joined),
            _ => Err(ResolveError::Unsupported(specifier.to_string())),
        }
    }

    fn apply(&self, specifier: &str, referrer: &Url, mapped: bool) -> Result<Resolved, ResolveError> {
        match classify_specifier(specifier) {
            SpecifierKind::Relative => {
                // Import-map targets are relative to the archive root, not to the importer.
                let base = if mapped {
                    Url::parse("file:///").map_err(|_| ResolveError::Invalid(specifier.to_string()))?
                } else {
                    referrer.clone()
                };
                self.relative(specifier, &base)
            }
            SpecifierKind::Builtin => {
                if let Some(to) = renamed_to(specifier) {
                    return Err(ResolveError::Renamed {
                        from: specifier.to_string(),
                        to: to.to_string(),
                    });
                }
                let name = builtin_alias(specifier).unwrap_or(specifier);
                if BUILTIN_MODULES.contains(&name) {
                    Ok(Resolved::Builtin(name.to_string()))
                } else {
                    Err(ResolveError::UnknownBuiltin(specifier.to_string()))
                }
            }
            // Operator SDKs are shims the build generates from their contracts (`crate::graph`).
            SpecifierKind::Sdk => Err(ResolveError::UnknownSdk(specifier.to_string())),
            SpecifierKind::Npm => {
                let u = self.cdn_url(specifier.trim_start_matches("npm:"))?;
                self.remote(u)
            }
            SpecifierKind::Jsr => {
                let u = self.cdn_url(&format!("jsr/{}", specifier.trim_start_matches("jsr:")))?;
                self.remote(u)
            }
            SpecifierKind::Remote => {
                let u = Url::parse(specifier).map_err(|_| ResolveError::Invalid(specifier.to_string()))?;
                self.remote(u)
            }
            SpecifierKind::File | SpecifierKind::Node | SpecifierKind::Bare => {
                Err(ResolveError::Unsupported(specifier.to_string()))
            }
        }
    }
}

impl SpecifierResolver for DefaultResolver {
    fn resolve(&self, specifier: &str, referrer: &Url) -> Result<Resolved, ResolveError> {
        // The import map is applied first, to everything but relative specifiers.
        if classify_specifier(specifier) != SpecifierKind::Relative {
            if let Some(target) = self.map_specifier(specifier) {
                return self.apply(&target, referrer, true);
            }
        }
        self.apply(specifier, referrer, false)
    }
}
