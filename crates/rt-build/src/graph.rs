#[derive(Clone)]
enum Origin {
    /// A file of the uploaded archive.
    Archive,
    /// Generated by the build: an operator SDK shim over `std:sdk` (`crate::sdk_shim`).
    Generated(String),
    /// Fetched through the egress guard.
    Remote,
}

fn fetch_failure(url: &Url, e: FetchError) -> BuildFailure {
    match e {
        FetchError::Denied(u) => fail(BuildFailReason::Fetch, format!("fetch of {u} was denied")),
        FetchError::NotFound(u) => fail(BuildFailReason::Fetch, format!("{u} not found")),
        FetchError::Timeout(u) => fail(BuildFailReason::Fetch, format!("fetch of {u} timed out")),
        FetchError::TooLarge => fail(BuildFailReason::TooLarge, format!("dependency {url} is too large")),
        FetchError::DigestMismatch { url, expected, actual } => fail(
            BuildFailReason::LockMismatch,
            format!("locked module {url} changed: expected {expected}, got {actual}"),
        ),
        FetchError::Upstream(u) => fail(BuildFailReason::Fetch, format!("upstream error fetching {u}")),
    }
}

struct Loaded {
    text: String,
    media: MediaType,
    name: String,
}

pub(crate) async fn build_deno(
    req: &BuildRequest,
    cx: &mut BuildCx,
    limits: &UploadLimits,
) -> Result<BuiltArtifact, BuildFailure> {
    let mut used = 0u64;
    let body = source_bytes(req, cx, &mut used).await?;
    // Extract the upload the way it was validated (its recorded Content-Type); uploads stored
    // before content types were recorded are sniffed.
    let content_type = cx.artifacts.content_type(&req.source_digest).await.ok().flatten();
    let ex = extract::extract(content_type.as_deref(), &body, limits).map_err(from_verr)?;
    drop(body);

    let entry_url = file_url(&ex.entry);
    let mut queue: VecDeque<(Url, Origin)> = VecDeque::new();
    let mut seen: HashSet<String> = HashSet::new();
    let mut modules: Vec<BundleModule> = Vec::new();
    let mut lock = RtLock::default();
    let mut handler_form = HandlerForm::Unknown;

    seen.insert(entry_url.to_string());
    queue.push_back((entry_url.clone(), Origin::Archive));
    // Remote modules of this build so far, from the network or the deps cache (`build.max_deps_mb`).
    let max_deps = cx.fetcher.max_total_bytes();
    let mut deps_bytes = 0u64;

    while let Some((url, origin)) = queue.pop_front() {
        let loaded = load(&url, &origin, &ex.files, req.lock.as_ref(), cx, &mut lock, &mut used).await?;
        if matches!(origin, Origin::Remote) {
            deps_bytes = deps_bytes.saturating_add(loaded.text.len() as u64);
            if max_deps.is_some_and(|max| deps_bytes > max) {
                return Err(fail(
                    BuildFailReason::TooLarge,
                    format!("dependencies total {deps_bytes} bytes, over the build.max_deps_mb limit (at {url})"),
                ));
            }
        }
        charge(cx, &mut used, loaded.text.len() as u64)?;

        if loaded.media == MediaType::Json {
            serde_json::from_str::<serde_json::Value>(&loaded.text).map_err(|e| {
                failure_with(
                    BuildFailReason::Syntax,
                    Diagnostic {
                        file: loaded.name.clone(),
                        line: e.line() as u32,
                        col: e.column() as u32,
                        message: format!("invalid JSON: {e}"),
                    },
                )
            })?;
            modules.push(BundleModule {
                specifier: url.to_string(),
                kind: ModuleKind::Json,
                source: loaded.text,
                source_map: None,
            });
            continue;
        }
        if !is_module_media(loaded.media) && loaded.media != MediaType::Unknown {
            return Err(failure_with(
                BuildFailReason::Resolve,
                Diagnostic {
                    file: loaded.name.clone(),
                    line: 1,
                    col: 1,
                    message: "unsupported module type (only JavaScript, TypeScript and JSON can be imported)"
                        .to_string(),
                },
            ));
        }
        let media = if loaded.media == MediaType::Unknown {
            MediaType::JavaScript
        } else {
            loaded.media
        };

        // transpile -> JS (+ source map); dependencies come from the emitted JS so type-only
        // imports do not drag modules into the bundle.
        let (emitted, source_map) = if needs_transpile(media) {
            let first = analyze::parse(&url, &loaded.name, &loaded.text, media)
                .map_err(|d| failure_with(BuildFailReason::Syntax, d))?;
            let out = analyze::transpile(first.source)
                .map_err(|e| fail(BuildFailReason::Syntax, format!("{}: {e}", loaded.name)))?;
            (out.text, out.source_map)
        } else {
            (loaded.text, None)
        };
        let parsed = analyze::parse(&url, &loaded.name, &emitted, MediaType::JavaScript)
            .map_err(|d| failure_with(BuildFailReason::Syntax, d))?;
        if url == entry_url {
            handler_form = parsed.handler_form;
        }

        // resolve every import; rewrite specifiers to canonical bundle specifiers.
        let mut edits: Vec<(usize, usize, String)> = Vec::new();
        for dep in &parsed.deps {
            let resolved = resolve_dep(&dep.spec, &url, &origin, &ex.import_map, cx).map_err(|msg| {
                failure_with(
                    BuildFailReason::Resolve,
                    Diagnostic {
                        file: loaded.name.clone(),
                        line: dep.line,
                        col: dep.col,
                        message: msg,
                    },
                )
            })?;
            let (canonical, next) = match resolved {
                Resolved::Builtin(n) => (n, None),
                Resolved::Remote(u) => (u.to_string(), Some((u, Origin::Remote))),
                Resolved::Generated { url, source } => (url.to_string(), Some((url, Origin::Generated(source)))),
                Resolved::Local(u) => {
                    let found = url_path(&u).is_some_and(|p| ex.files.contains_key(&p));
                    if !found {
                        return Err(failure_with(
                            BuildFailReason::Resolve,
                            Diagnostic {
                                file: loaded.name.clone(),
                                line: dep.line,
                                col: dep.col,
                                message: format!("cannot resolve `{}`: no such file in the upload", dep.spec),
                            },
                        ));
                    }
                    (u.to_string(), Some((u, Origin::Archive)))
                }
            };
            if canonical != dep.spec {
                edits.push((dep.start, dep.end, js_string(&canonical)));
            }
            if let Some((next_url, next_origin)) = next {
                if seen.insert(next_url.to_string()) {
                    queue.push_back((next_url, next_origin));
                }
            }
        }
        let source = if edits.is_empty() {
            emitted
        } else {
            analyze::splice(&emitted, edits)
        };
        charge(cx, &mut used, source.len() as u64)?;
        modules.push(BundleModule {
            specifier: url.to_string(),
            kind: ModuleKind::Js,
            source,
            source_map,
        });
    }

    let lock_digest = lock.digest();
    let mut bundle = Bundle::new(entry_url.to_string(), handler_form, Some(lock_digest));
    bundle.modules = modules;
    bundle.canonicalize();
    let bundle_bytes = bundle.to_bytes();
    let bundle_digest = Digest::of(&bundle_bytes);

    let mut files = vec![BuiltFile {
        name: "bundle".to_string(),
        bytes: Bytes::from(bundle_bytes),
    }];
    if let Some(producer) = cx.code_cache.clone() {
        let cache = producer.produce(&bundle)?;
        files.push(BuiltFile {
            name: "code_cache.bin".to_string(),
            bytes: Bytes::from(cache.to_bytes()),
        });
    }
    Ok(BuiltArtifact {
        key: req.key,
        files,
        lock: Some(lock),
        bundle_digest: Some(bundle_digest),
    })
}

/// An operator SDK import of a tenant module, as the shim generated from the published contracts:
/// `std:sdk` (one named proxy per SDK) or `sdk:<name>`. `None` for any other specifier.
fn sdk_shim(spec: &str, cx: &BuildCx) -> Option<Result<Resolved, String>> {
    let catalog = || cx.sdks.as_ref().map(|c| c.sdks()).unwrap_or_default();
    if spec == "std:sdk" {
        let url = Url::parse(crate::sdk_shim::STD_SDK_SHIM).ok()?;
        return Some(Ok(Resolved::Generated {
            url,
            source: crate::sdk_shim::std_sdk_shim(&catalog()),
        }));
    }
    let name = spec.strip_prefix("sdk:")?;
    let sdks = catalog();
    Some(match (sdks.get(name), crate::sdk_shim::sdk_shim_url(name)) {
        (Some(members), Some(url)) => Ok(Resolved::Generated {
            url,
            source: crate::sdk_shim::named_sdk_shim(name, members),
        }),
        _ => Err(format!(
            "unknown sdk `{spec}`: no operator SDK of that name is published"
        )),
    })
}

fn resolve_dep(
    spec: &str,
    url: &Url,
    origin: &Origin,
    import_map: &BTreeMap<String, String>,
    cx: &BuildCx,
) -> Result<Resolved, String> {
    // A generated shim imports the runtime's own `std:sdk`.
    if !matches!(origin, Origin::Generated(_)) {
        if let Some(shim) = sdk_shim(spec, cx) {
            return shim;
        }
    }
    // The upload's own import map (`rt.json` / the JSON bundle's `imports`) is applied first: the
    // node-wide resolver does not know it. A relative target is relative to the upload root.
    if !matches!(origin, Origin::Generated(_)) && classify_specifier(spec) != SpecifierKind::Relative {
        if let Some(target) = map_specifier(import_map, spec) {
            if let Some(shim) = sdk_shim(&target, cx) {
                return shim;
            }
            let root;
            let base = if classify_specifier(&target) == SpecifierKind::Relative {
                root = file_url("");
                &root
            } else {
                url
            };
            return cx.resolver.resolve(&target, base).map_err(|e| e.to_string());
        }
    }
    cx.resolver.resolve(spec, url).map_err(|e| e.to_string())
}

async fn load(
    url: &Url,
    origin: &Origin,
    files: &BTreeMap<String, Bytes>,
    prior: Option<&RtLock>,
    cx: &mut BuildCx,
    lock: &mut RtLock,
    used: &mut u64,
) -> Result<Loaded, BuildFailure> {
    match origin {
        Origin::Archive => {
            let path = url_path(url).ok_or_else(|| fail(BuildFailReason::Internal, format!("bad module url {url}")))?;
            let content = files.get(&path).ok_or_else(|| {
                fail(
                    BuildFailReason::Resolve,
                    format!("module `{path}` is not in the upload"),
                )
            })?;
            let text = String::from_utf8(content.to_vec()).map_err(|_| {
                failure_with(
                    BuildFailReason::Syntax,
                    Diagnostic {
                        file: path.clone(),
                        line: 1,
                        col: 1,
                        message: "source is not valid UTF-8".to_string(),
                    },
                )
            })?;
            let media = crate::sniff::media_type_of(&path);
            Ok(Loaded {
                text,
                media,
                name: path,
            })
        }
        Origin::Generated(text) => Ok(Loaded {
            text: text.clone(),
            media: MediaType::JavaScript,
            name: url.to_string(),
        }),
        Origin::Remote => {
            let locked = prior.and_then(|l| l.entries.get(url.as_str()));
            let expected = locked.map(|e| e.digest);
            let got = cx
                .fetcher
                .fetch(url, expected)
                .await
                .map_err(|e| fetch_failure(url, e))?;
            if let Some(l) = prior {
                l.verify(url.as_str(), &got.digest).map_err(|m| {
                    fail(
                        BuildFailReason::LockMismatch,
                        format!(
                            "locked module {} changed: expected {}, got {}",
                            m.url, m.expected, m.actual
                        ),
                    )
                })?;
            }
            charge(cx, used, got.bytes.len() as u64)?;
            // The lock's recorded type wins: the locked bytes compile exactly as in the first build,
            // whatever the network or a cache reports for the URL now (and vendored bytes carry no
            // header at all). A module with no type and no extension builds as JavaScript below.
            let content_type = locked
                .and_then(|e| e.content_type.clone())
                .or_else(|| got.content_type.clone());
            lock.record_typed(url.as_str(), got.digest, got.bytes.len() as u64, content_type.clone());
            let text = String::from_utf8(got.bytes.to_vec())
                .map_err(|_| fail(BuildFailReason::Syntax, format!("{url} is not valid UTF-8")))?;
            let media = match &content_type {
                Some(ct) => MediaType::from_content_type(url, ct),
                None => MediaType::from_specifier(url),
            };
            Ok(Loaded {
                text,
                media,
                name: url.to_string(),
            })
        }
    }
}
