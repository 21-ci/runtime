fn fail(reason: BuildFailReason, message: impl Into<String>) -> BuildFailure {
    BuildFailure::new(reason, message)
}

fn failure_with(reason: BuildFailReason, d: Diagnostic) -> BuildFailure {
    BuildFailure {
        reason,
        message: format!("{}:{}:{}: {}", d.file, d.line, d.col, d.message),
        diagnostics: vec![d],
    }
}

fn from_verr(e: VErr) -> BuildFailure {
    match e {
        VErr::Invalid(d) => {
            let message = d
                .first()
                .map(|d| format!("{}: {}", d.file, d.message))
                .unwrap_or_default();
            BuildFailure {
                reason: BuildFailReason::Syntax,
                message,
                diagnostics: d,
            }
        }
        VErr::InvalidArtifact(m) => fail(BuildFailReason::Internal, m),
        VErr::TooLarge(m) => fail(BuildFailReason::TooLarge, m),
    }
}

/// Charge `add` bytes of working set to the build reservation; refusal is `oom`.
fn charge(cx: &mut BuildCx, used: &mut u64, add: u64) -> Result<(), BuildFailure> {
    *used = used.saturating_add(add);
    let held = cx.reservation.bytes();
    if *used > held && !cx.reservation.try_grow(*used - held) {
        return Err(fail(
            BuildFailReason::Oom,
            format!("build working set of {} bytes exceeds its memory reservation", *used),
        ));
    }
    Ok(())
}

async fn source_bytes(req: &BuildRequest, cx: &mut BuildCx, used: &mut u64) -> Result<Bytes, BuildFailure> {
    let body = cx
        .artifacts
        .get(&req.source_digest)
        .await
        .map_err(|e| fail(BuildFailReason::Internal, format!("source artifact unavailable: {e}")))?;
    charge(cx, used, body.len() as u64)?;
    Ok(body)
}

// ---------------------------------------------------------------------------------------------
// WASM
// ---------------------------------------------------------------------------------------------

pub(crate) async fn build_wasm(
    req: &BuildRequest,
    cx: &mut BuildCx,
    limits: &UploadLimits,
) -> Result<BuiltArtifact, BuildFailure> {
    let mut used = 0u64;
    let body = source_bytes(req, cx, &mut used).await?;
    if body.len() as u64 > limits.max_wasm {
        return Err(fail(BuildFailReason::TooLarge, "component too large"));
    }
    // T3 is trusted storage, but a build must never feed a non-component to the compiler.
    crate::validate::check_component(&body).map_err(from_verr)?;
    let Some(precompiler) = cx.precompiler.clone() else {
        return Err(fail(BuildFailReason::Internal, "no ComponentPrecompiler is configured"));
    };
    let cwasm = precompiler.precompile(&body)?;
    charge(cx, &mut used, cwasm.len() as u64)?;
    Ok(BuiltArtifact {
        key: req.key,
        files: vec![BuiltFile {
            name: "component.cwasm".to_string(),
            bytes: Bytes::from(cwasm),
        }],
        lock: None,
        bundle_digest: None,
    })
}

