fn exportable(name: &str) -> bool {
    let b = name.as_bytes();
    !b.is_empty()
        && (b[0].is_ascii_alphabetic() || b[0] == b'_' || b[0] == b'$')
        && b.iter().all(|c| c.is_ascii_alphanumeric() || *c == b'_' || *c == b'$')
        && !RESERVED.contains(&name)
}

/// `std:sdk` for a tenant: the runtime module's `sdk` and `SdkError`, plus one named proxy per
/// published SDK.
pub fn std_sdk_shim(catalog: &BTreeMap<String, Vec<String>>) -> String {
    let mut out = String::from(
        "// Generated by the runtime from the published SDK contracts: no SDK code.\n\
         import { sdk, SdkError } from \"std:sdk\";\nexport { sdk, SdkError };\n",
    );
    for name in catalog.keys().filter(|n| exportable(n)) {
        out.push_str(&format!("export const {name} = sdk(\"{name}\");\n"));
    }
    out
}

/// `sdk:<name>` for a tenant: the SDK's proxy as the default export, and its top-level members.
pub fn named_sdk_shim(name: &str, members: &[String]) -> String {
    let mut out = format!(
        "// Generated by the runtime from the contract of the SDK `{name}`: no SDK code.\n\
         import {{ sdk }} from \"std:sdk\";\nconst {name} = sdk(\"{name}\");\nexport default {name};\n"
    );
    for m in members.iter().filter(|m| exportable(m) && *m != name) {
        out.push_str(&format!("export const {m} = {name}.{m};\n"));
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn shims_export_the_contract_and_no_sdk_code() {
        let mut c = BTreeMap::new();
        c.insert(
            "acme".to_string(),
            vec!["ping".to_string(), "invoices".to_string(), "delete".to_string()],
        );
        c.insert("billing".to_string(), vec![]);
        let std = std_sdk_shim(&c);
        assert!(std.contains("import { sdk, SdkError } from \"std:sdk\";"));
        assert!(std.contains("export const acme = sdk(\"acme\");\nexport const billing = sdk(\"billing\");"));
        let named = named_sdk_shim("acme", &c["acme"]);
        assert!(named.contains("export default acme;"));
        assert!(named.contains("export const ping = acme.ping;\nexport const invoices = acme.invoices;"));
        assert!(
            !named.contains("export const delete"),
            "a reserved word is reachable as acme.delete only"
        );
        assert_eq!(sdk_shim_url("acme").unwrap().as_str(), "file:///__sdk__/acme.js");
        assert!(sdk_shim_url("../x").is_none());
    }
}
