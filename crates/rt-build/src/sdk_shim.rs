//! Operator SDK imports: contract at build, bind at run time.
//!
//! A tenant build never contains SDK code. `import { acme } from "std:sdk"` and
//! `import acme from "sdk:acme"` resolve to modules generated here from the published contract
//! (the SDK names and each one's top-level members) over the runtime's `sdk(name)` proxy. Which
//! release runs is decided per call by the caller's grants, so an SDK update, rollback or
//! removal never rebuilds or redeploys the tenant.

use std::collections::BTreeMap;

use url::Url;

/// The SDKs a build can import: the published ones that are not removed.
pub trait SdkCatalog: Send + Sync {
    /// SDK name -> the top-level members of its current (`stable`) contract.
    fn sdks(&self) -> BTreeMap<String, Vec<String>>;
}

/// A fixed catalog (tests, embedders).
#[derive(Clone, Debug, Default)]
pub struct StaticSdkCatalog(pub BTreeMap<String, Vec<String>>);

impl SdkCatalog for StaticSdkCatalog {
    fn sdks(&self) -> BTreeMap<String, Vec<String>> {
        self.0.clone()
    }
}

/// The module every tenant import of `std:sdk` is replaced with.
pub const STD_SDK_SHIM: &str = "file:///__sdk__/std.js";

/// The module a tenant import of `sdk:<name>` is replaced with.
pub fn sdk_shim_url(name: &str) -> Option<Url> {
    rt_types::valid_sdk_name(name)
        .then(|| Url::parse(&format!("file:///__sdk__/{name}.js")).ok())
        .flatten()
}

